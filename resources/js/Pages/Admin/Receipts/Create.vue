<script setup>
import { ref, watch, computed, nextTick } from 'vue';
import { useForm, Link } from '@inertiajs/vue3';
import AdminLayout from '@/Layouts/AdminLayout.vue';
import FlashMessages from '@/Components/FlashMessages.vue';
import ReceiptVoucher from '@/Components/ReceiptVoucher.vue';
import EnvoySignatureModal from '@/Components/EnvoySignatureModal.vue';
import { numberToNairaWords } from '@/lib/numberToWords';
import { trimCanvasToDataUrl } from '@/lib/trimCanvas';

defineOptions({ layout: AdminLayout });

const props = defineProps({
    customers: { type: Array, default: () => [] },
    defaultEnvoySignature: { type: String, default: '' },
});

const today = new Date().toISOString().split('T')[0];

// Step state: 1 = Customer & Basics, 2 = Payment Details, 3 = Signature & Finalize
const currentStep = ref(1);

const form = useForm({
    receipt_date: today,
    customer_id: null,
    customer_name: '',
    customer_phone: '',
    customer_email: '',
    amount: '',
    amount_in_words: '',
    payment_for: '',
    payment_method: 'Cash',
    customer_signature: '',
    envoy_signature: props.defaultEnvoySignature || '',
    signatory_title: 'Authorized Signatory',
    notes: '',
    send_email: false,
    open_whatsapp: false,
});

// Envoy signature modal
const envoySigModalOpen = ref(false);

function openEnvoySigModal() {
    envoySigModalOpen.value = true;
}

function onEnvoySigSaved(sig) {
    form.envoy_signature = sig;
}

// Step validation errors
const stepErrors = ref({});

// Signature mode: 'later' (default) or 'now' (sign on-screen immediately)
const signatureMode = ref('later');

// Canvas ref & drawing states
const canvas = ref(null);
const isDrawing = ref(false);
const hasDrawn = ref(false);
const lastPos = ref({ x: 0, y: 0 });

function getCanvasPos(e, el) {
    const rect = el.getBoundingClientRect();
    const src = e.touches ? e.touches[0] : e;
    return {
        x: (src.clientX - rect.left) * (el.width / rect.width),
        y: (src.clientY - rect.top) * (el.height / rect.height),
    };
}

function startDraw(e) {
    if (e.cancelable) e.preventDefault();
    isDrawing.value = true;
    lastPos.value = getCanvasPos(e, canvas.value);
}

function draw(e) {
    if (!isDrawing.value || !canvas.value) return;
    if (e.cancelable) e.preventDefault();
    const ctx = canvas.value.getContext('2d');
    const pos = getCanvasPos(e, canvas.value);
    ctx.strokeStyle = '#0a2456';
    ctx.lineWidth = 3;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    ctx.beginPath();
    ctx.moveTo(lastPos.value.x, lastPos.value.y);
    ctx.lineTo(pos.x, pos.y);
    ctx.stroke();
    lastPos.value = pos;
    hasDrawn.value = true;
    form.customer_signature = canvas.value.toDataURL('image/png');
}

function stopDraw() {
    if (!isDrawing.value) return;
    isDrawing.value = false;
    if (hasDrawn.value && canvas.value) {
        form.customer_signature = trimCanvasToDataUrl(canvas.value);
    }
}

function clearSignature() {
    if (canvas.value) {
        const ctx = canvas.value.getContext('2d');
        ctx.clearRect(0, 0, canvas.value.width, canvas.value.height);
    }
    hasDrawn.value = false;
    form.customer_signature = '';
}

function switchSignatureMode(mode) {
    signatureMode.value = mode;
    if (mode === 'later') {
        form.customer_signature = '';
    } else if (mode === 'now') {
        nextTick(() => {
            if (canvas.value && hasDrawn.value) {
                form.customer_signature = trimCanvasToDataUrl(canvas.value);
            }
        });
    }
}

// Auto-convert amount to words when amount changes (unless user explicitly customized it)
const wordsAutoGenerated = ref(true);

watch(() => form.amount, (newVal) => {
    if (wordsAutoGenerated.value) {
        form.amount_in_words = numberToNairaWords(newVal);
    }
});

function onWordsManualEdit() {
    wordsAutoGenerated.value = false;
}

function regenerateWords() {
    wordsAutoGenerated.value = true;
    form.amount_in_words = numberToNairaWords(form.amount);
}

// When a customer is selected from the dropdown
function onCustomerSelect(e) {
    const custId = e.target.value;
    if (!custId) {
        form.customer_id = null;
        return;
    }
    const cust = props.customers.find((c) => String(c.id) === String(custId));
    if (cust) {
        form.customer_id = cust.id;
        form.customer_name = cust.name;
        if (cust.phone) form.customer_phone = cust.phone;
        if (cust.email) form.customer_email = cust.email;
        if (stepErrors.value.customer_name) delete stepErrors.value.customer_name;
    }
}

// Quick presets for "payment for"
const commonPayments = [
    'Supply & Installation of Solar Inverter System',
    'Procurement of Deep Cycle Solar Batteries',
    'Supply of Monocrystalline Solar Panels',
    'CCTV Security Camera Installation & Cabling',
    'Electrical Installation & Maintenance Services',
    'Solar Generator Setup & Maintenance',
];

function setPaymentFor(text) {
    form.payment_for = text;
    if (stepErrors.value.payment_for) delete stepErrors.value.payment_for;
}

// Validation per step
function validateStep(step) {
    stepErrors.value = {};

    if (step === 1) {
        if (!form.receipt_date) {
            stepErrors.value.receipt_date = 'Receipt date is required';
        }
        if (!form.customer_name || !form.customer_name.trim()) {
            stepErrors.value.customer_name = 'Customer full name is required';
        }
        if (!form.payment_method) {
            stepErrors.value.payment_method = 'Payment method is required';
        }
        return Object.keys(stepErrors.value).length === 0;
    }

    if (step === 2) {
        if (!form.amount || Number(form.amount) <= 0) {
            stepErrors.value.amount = 'Please enter a valid amount greater than 0';
        }
        if (!form.payment_for || !form.payment_for.trim()) {
            stepErrors.value.payment_for = 'Payment description is required';
        }
        return Object.keys(stepErrors.value).length === 0;
    }

    return true;
}

function nextStep() {
    if (validateStep(currentStep.value)) {
        if (currentStep.value < 3) {
            currentStep.value++;
        }
    }
}

function prevStep() {
    stepErrors.value = {};
    if (currentStep.value > 1) {
        currentStep.value--;
    }
}

function goToStep(step) {
    if (step < currentStep.value) {
        stepErrors.value = {};
        currentStep.value = step;
        return;
    }

    // If jumping forward, validate intervening steps
    for (let s = currentStep.value; s < step; s++) {
        if (!validateStep(s)) {
            currentStep.value = s;
            return;
        }
    }
    currentStep.value = step;
}

// Receipt object for live preview
const previewReceipt = computed(() => {
    return {
        ref_id: 'REC-PREVIEW',
        receipt_date: form.receipt_date,
        customer_name: form.customer_name || 'Customer Full Name',
        amount: form.amount || 0,
        amount_in_words: form.amount_in_words || 'Zero Naira Only',
        payment_for: form.payment_for || 'Description of goods / services rendered',
        payment_method: form.payment_method,
        customer_signature: form.customer_signature,
        envoy_signature: form.envoy_signature,
        signatory_title: form.signatory_title || 'Authorized Signatory',
    };
});

function submit() {
    if (!validateStep(1) || !validateStep(2)) {
        return;
    }
    if (signatureMode.value === 'now' && hasDrawn.value && canvas.value) {
        form.customer_signature = trimCanvasToDataUrl(canvas.value);
    }
    form.post('/admin/receipts');
}
</script>

